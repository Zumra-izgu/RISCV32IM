/*
It takes a small amount of information about 
the instruction and produces the alu_ctrl signal 
that drives the ALU.
*/

`include "defines.vh"


module alu_control (
    

    /*
    alu_op is a 2-bit signal, which is generated by 
    the control unit and used to decide the initial 
    category of the instruction. It is a runtime signal.
    It has nothing to do with the header file.


    Note: Following input and output variables can be 
    found in the "control unit" of RISCV, which is located
    after the second clock.
    */

    input wire [1:0] alu_op, //2 bits
    input wire [2:0] funct3,//3 bits
    input wire [6:0] funct7,//7 bits

    output reg [4:0] alu_ctrl //5 bits
);


    always @(*) begin
        case(alu_op)

            //ADD and SUB flags 

            2'b00: alu_ctrl = `ALU_ADD;
            2'b01: alu_ctrl = `ALU_SUB;


            //M-EXTENSIONS flag (R-Type is included as else case)

            2'b10: begin
                if (funct7 == `F7_MULDIV) begin
                    case(funct3)
                        `F3_MUL:    alu_ctrl = `ALU_MUL;
                        `F3_MULH:   alu_ctrl = `ALU_MULH;
                        `F3_MULHSU: alu_ctrl = `ALU_MULHSU;
                        `F3_MULHU:  alu_ctrl = `ALU_MULHU;
                        `F3_DIV:    alu_ctrl = `ALU_DIV;
                        `F3_DIVU:   alu_ctrl = `ALU_DIVU;
                        `F3_REM:    alu_ctrl = `ALU_REM;
                        `F3_REMU:   alu_ctrl = `ALU_REMU;

                        default:    alu_ctrl = `ALU_ADD;

                    endcase

            
                end else begin 

                case(funct3)
                    `F3_ADD:    alu_ctrl = (funct7 == `F7_SUB) ? `ALU_SUB: `ALU_ADD;
                    `F3_XOR:    alu_ctrl = `ALU_XOR;
                    `F3_OR:     alu_ctrl = `ALU_OR; 
                    `F3_AND:    alu_ctrl = `ALU_AND;
                    `F3_SLL:    alu_ctrl = `ALU_SLL;
                    
                    `F3_SRL:    alu_ctrl = (funct7 == `F7_SRA) ? `ALU_SRA : `ALU_SRL;
                    `F3_SLT:    alu_ctrl = `ALU_SLT;
                    `F3_SLTU:   alu_ctrl = `ALU_SLTU;
                    default:    alu_ctrl = `ALU_ADD;

                endcase

            end 
            
        end

        


            // I-TYPE 
            2'b11: begin
                case(funct3)
                    `F3_ADDI:   alu_ctrl = `ALU_ADD;
                    `F3_XORI:   alu_ctrl = `ALU_XOR;
                    `F3_ORI:    alu_ctrl = `ALU_OR;
                    `F3_ANDI:   alu_ctrl = `ALU_AND;
                    `F3_SLLI:   alu_ctrl = `ALU_SLL;
                    `F3_SRLI:   alu_ctrl = (funct7 == `F7_SRA) ? `ALU_SRA : `ALU_SRL;
                    `F3_SLTI:   alu_ctrl = `ALU_SLT;
                    `F3_SLTUI:  alu_ctrl = `ALU_SLTU;
                    default:    alu_ctrl = `ALU_ADD;

                endcase
            end
            //DEFAULT TYPE
            default: alu_ctrl = `ALU_ADD;

        endcase    
    
    end 
endmodule 
















    